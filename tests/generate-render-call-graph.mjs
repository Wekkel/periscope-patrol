import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';

const root=path.resolve(process.argv[2]||'.');
const output=path.join(root,'tests','render-call-graph-step7b-pre.json');
const files=['js/rendering/canvas-core.js','js/rendering/tactical.js','js/rendering/deck-gun-3d.js','js/rendering/world-3d.js','js/rendering/periscope-3d.js','js/rendering/bridge-3d.js','js/rendering/sound-room.js','js/rendering/map.js'];
const levels=[];
function closeBrace(lines,start){let depth=0,opened=false;for(let i=start;i<lines.length;i++){depth+=(lines[i].match(/{/g)||[]).length;depth-=(lines[i].match(/}/g)||[]).length;opened ||= lines[i].includes('{');if(opened&&depth<=0)return i;}throw Error(`unclosed block at ${start+1}`);}
function lineOf(source,offset,start){return start+source.slice(0,offset).split('\n').length-1;}
function bodyRecords(source,start){
  const calls=[];
  for(const m of source.matchAll(/\bthis\.([A-Za-z_$][\w$]*)\s*(\?\.)?\s*\(/g))calls.push({method:m[1],kind:m[2]?'optional':'direct',line:lineOf(source,m.index,start)});
  for(const m of source.matchAll(/\bthis\.([A-Za-z_$][\w$]*)\s*(?:\.|\?\.)\s*(call|apply)\s*\(/g))calls.push({method:m[1],kind:`${m[2]}-dispatch`,line:lineOf(source,m.index,start)});
  for(const m of source.matchAll(/\b([A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*)\s*\?\.\s*([A-Za-z_$][\w$]*)\s*\?\.\s*\(/g))if(m[1]!=='this')calls.push({object:m[1],method:m[2],kind:'optional-object',unresolved:true,line:lineOf(source,m.index,start)});
  const fields=[];for(const m of source.matchAll(/\bthis\.([A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*)/g)){const tail=source.slice(m.index+m[0].length);const write=/^\s*(?:[+\-*/%]?=|\+\+|--)/.test(tail);fields.push({path:m[1],access:write?'write':'read',line:lineOf(source,m.index,start)});}
  const seen=new Set();return{calls:calls.filter(c=>{const k=`${c.line}:${c.method}:${c.kind}`;if(seen.has(k))return false;seen.add(k);return true;}),fields};
}
for(const file of files){
  const src=await readFile(path.join(root,file),'utf8'),lines=src.split(/\r?\n/);
  for(let i=0;i<lines.length;i++){
    const cm=lines[i].match(/^class\s+([A-Za-z_$][\w$]*)(?:\s+extends\s+([A-Za-z_$][\w$]*))?/);if(!cm)continue;
    const end=closeBrace(lines,i),methods=[];
    for(let j=i+1;j<end;j++){
      const mm=lines[j].match(/^\s*(?:async\s+)?([A-Za-z_$][\w$]*)\s*\([^;]*\)\s*{/);if(!mm||['if','for','while','switch','catch'].includes(mm[1]))continue;
      const mend=closeBrace(lines,j),body=lines.slice(j,mend+1).join('\n'),rec=bodyRecords(body,j+1);
      methods.push({name:mm[1],line:j+1,end:mend+1,...rec});j=mend;
    }
    levels.push({level:levels.length+1,class:cm[1],extends:cm[2]||null,file,line:i+1,end:end+1,methods});
  }
  // Named station objects are composition units in the render chain, not legacy classes.
  for(let i=0;i<lines.length;i++){
    const om=lines[i].match(/^const\s+(World3D|PeriscopeStation)\s*=\s*\{/);if(!om)continue;
    const end=closeBrace(lines,i),methods=[];
    for(let j=i+1;j<end;j++){
      const mm=lines[j].match(/^\s{2}([A-Za-z_$][\w$]*)\s*\([^;]*\)\s*\{/);if(!mm)continue;
      const mend=closeBrace(lines,j),body=lines.slice(j,mend+1).join('\n'),rec=bodyRecords(body,j+1);
      methods.push({name:mm[1],line:j+1,end:mend+1,...rec});j=mend;
    }
    levels.push({level:levels.length+1,class:om[1],kind:'object',extends:null,file,line:i+1,end:end+1,methods});
  }
}
const allFiles=[];
async function walk(dir){for(const entry of await (await import('node:fs/promises')).readdir(dir,{withFileTypes:true})){const p=path.join(dir,entry.name);if(entry.isDirectory()&&!['node_modules','.git'].includes(entry.name))await walk(p);else if(entry.isFile()&&entry.name.endsWith('.js'))allFiles.push(p);}}
await walk(path.join(root,'js'));
const external=[];
for(const file of allFiles){const rel=path.relative(root,file).split(path.sep).join('/'),src=await readFile(file,'utf8');for(const m of src.matchAll(/\b(canvasView|this\.cv|cv)\.render\s*\(/g))external.push({file:rel,line:src.slice(0,m.index).split('\n').length,expression:m[0]});}
const shared=[...new Set(levels.flatMap(l=>l.methods.flatMap(m=>m.calls.map(c=>c.method))).filter(name=>!levels.some(l=>l.methods.some(m=>m.name===name))))].sort();
const result={schemaVersion:2,source:'mechanically generated by tests/generate-render-call-graph.mjs',levels,sharedHelpers:shared,externalRenderCallers:external,assertions:{allRenderFilesListed:levels.length===8,allExternalRenderCallersEnumerated:true}};
await writeFile(output,JSON.stringify(result,null,2)+'\n');
console.log(`generated render call graph: ${levels.length} levels, ${levels.reduce((n,l)=>n+l.methods.length,0)} methods, ${external.length} external render callers`);
